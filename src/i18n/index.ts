const DICTIONARY: Record<LanguageCode, Translations> = {
  en,
  fil,
  es,
  ja,
  ko,
  de,
  fr,
  zh,
};

export function translate(key: TranslationKey, lang: LanguageCode = 'en'): string {
  const currentDict = DICTIONARY[lang] || DICTIONARY.en;
  return currentDict[key] || DICTIONARY.en[key] || key;
}

export function useTranslation() {
  const { settings } = useSettings();
  const lang = settings.language || 'en';
  return {
    t: (key: TranslationKey) => translate(key, lang),
    language: lang,
  };
}
